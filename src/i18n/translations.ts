export function getLocalizedStreakTitle(days: number, lang: AppLanguage): string {
  const tiers = [30, 25, 20, 15, 10, 5, 0];
  const matched = tiers.find((t) => days >= t) ?? 0;
  return TITLE_TRANSLATIONS[lang][matched] ?? TITLE_TRANSLATIONS.ar[matched];
}

