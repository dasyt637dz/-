export function getDailyQuotesForDay(dayNumber: number): DailyQuotesPair {
  if (dayNumber <= 0) return DAILY_QUOTES_BY_DAY[0];
  if (dayNumber <= DAILY_QUOTES_BY_DAY.length) {
    return DAILY_QUOTES_BY_DAY[dayNumber - 1];
  }
  const idx = (dayNumber - DAILY_QUOTES_BY_DAY.length - 1) % STABILITY_QUOTES.length;
  return STABILITY_QUOTES[idx];
}

